export function suggestFiscalInfo(productName: string): { ncm: string, cest: string } | null {
  if (!productName) return null;
  
  const nameLower = productName.toLowerCase();
  
  // Coletamos todos os matches possíveis
  const matches: { ncm: string, cest: string, keywordLen: number }[] = [];
  
  for (const mapping of FISCAL_MAPPINGS) {
    const keywords = mapping.pecas.split(/[,/]/).map(k => k.trim().toLowerCase()).filter(k => k.length > 2);
    for (const keyword of keywords) {
      if (nameLower.includes(keyword)) {
        matches.push({ ncm: mapping.ncm, cest: mapping.cest, keywordLen: keyword.length });
      }
    }
  }
  
  if (matches.length === 0) return null;
  
  // Retorna o match com a maior keyword (mais específico)
  // Ex: "Motor de Partida" match com "Motor" (5) e "Motor de Partida" (16) -> Ganha 16
  return matches.sort((a, b) => b.keywordLen - a.keywordLen)[0];
}
